# Лабораторная работа №3. Задание 3, пункт 2: вычисление e^(-x) по ряду Тейлора.
x_start = float(input('Введите X начальное: '))  # Считываем начало интервала.
x_end = float(input('Введите X конечное: '))  # Считываем конец интервала.
dx = float(input('Введите шаг dx: '))  # Считываем шаг аргумента.
eps = float(input('Введите точность epsilon (например, 0.0001): '))  # Считываем требуемую точность.
if dx <= 0 or x_start > x_end or eps <= 0:  # Проверяем введённые параметры.
    print('Ошибка: dx и epsilon должны быть больше нуля, X начальное не больше X конечного.')  # Выводим сообщение об ошибке.
else:  # При корректных параметрах вычисляем ряд.
    print('\nВычисление e^(-x) по ряду Тейлора')  # Выводим заголовок таблицы.
    print('{:>10} {:>16} {:>12}'.format('X', 'e^(-x)', 'Члены ряда'))  # Выводим названия столбцов.
    print('-' * 42)  # Рисуем разделительную линию.
    x = x_start  # Устанавливаем первый аргумент.
    while x <= x_end + dx * 1e-9:  # Перебираем аргументы до конца интервала.
        term = 1.0  # Первый член ряда равен единице.
        total = term  # Начальная сумма состоит из первого члена.
        count = 1  # Счётчик просуммированных членов начинается с единицы.
        n = 1  # Задаём номер следующего члена ряда.
        while True:  # Запускаем цикл суммирования членов ряда.
            term = term * (-x) / n  # Находим следующий член по рекуррентной формуле.
            total += term  # Добавляем новый член к сумме.
            count += 1  # Увеличиваем счётчик членов ряда.
            n += 1  # Переходим к следующему номеру члена.
            if abs(term) < eps:  # Проверяем, стал ли очередной член меньше точности.
                break  # Завершаем суммирование при достижении точности.
            if count >= 10000:  # Проверяем защитное ограничение числа итераций.
                break  # Прерываем цикл, чтобы избежать бесконечного выполнения.
        print('{:10.3f} {:16.8f} {:12d}'.format(x, total, count))  # Выводим x, сумму ряда и число членов.
        x += dx  # Переходим к следующему значению аргумента.
input('\nНажмите Enter, чтобы закрыть программу...')  # Удерживаем окно открытым.
