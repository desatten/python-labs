from math import sqrt  # Подключаем квадратный корень для дуги окружности.

def calculate_y(x):  # Функция определяет значение y по заданному x.
    if x < -8:  # Проверяем левый горизонтальный участок.
        return -3.0  # Возвращаем постоянное значение y.
    elif x < -3:  # Проверяем участок наклонной прямой.
        return 0.6 * x + 1.8  # Вычисляем прямую через точки (-8,-3) и (-3,0).
    elif x <= 3:  # Проверяем нижнюю полуокружность радиуса 3.
        return -sqrt(max(0.0, 9 - x ** 2))  # Вычисляем отрицательную ветвь окружности.
    elif x < 5:  # Проверяем прямой участок от x=3 до x=5.
        return x - 3  # Вычисляем значение прямой.
    else:  # Все значения x от 5 и правее.
        return 3.0  # Возвращаем значение правого горизонтального участка.

x_start = float(input('Введите X начальное: '))  # Считываем начало интервала.
x_end = float(input('Введите X конечное: '))  # Считываем конец интервала.
dx = float(input('Введите шаг dx: '))  # Считываем шаг изменения x.
if dx <= 0 or x_start > x_end:  # Проверяем корректность интервала и шага.
    print('Ошибка: dx должен быть больше нуля, X начальное не больше X конечного.')  # Сообщаем об ошибке.
else:  # Если параметры корректны, строим таблицу.
    print('\nТаблица значений функции, вариант 2')  # Печатаем название таблицы.
    print('{:>10} {:>12}'.format('X', 'Y'))  # Печатаем заголовки столбцов.
    print('-' * 24)  # Печатаем разделительную линию.
    x = x_start  # Устанавливаем аргумент на начало интервала.
    while x <= x_end + dx * 1e-9:  # Повторяем, пока x не превысит конец интервала.
        y = calculate_y(x)  # Вычисляем значение функции.
        print('{:10.2f} {:12.2f}'.format(x, y))  # Выводим x и y в строку таблицы.
        x += dx  # Увеличиваем аргумент на шаг dx.
input('\nНажмите Enter, чтобы закрыть программу...')  # Удерживаем окно открытым.
