# Лабораторная работа №3. Задание 2. Десять случайных выстрелов по мишени.
from random import uniform  # Подключаем генератор случайных вещественных чисел.

def is_hit(x, y):  # Функция проверяет, попадает ли точка в область варианта 2.
    in_upper_part = x <= 0 and y >= 0 and x ** 2 + y ** 2 <= 4  # Проверяем четверть круга во II четверти.
    in_lower_part = x >= 0 and y <= 0 and y >= -2 * x and y >= 2 * x - 4  # Проверяем нижний треугольник.
    return in_upper_part or in_lower_part  # Возвращаем True, если точка входит хотя бы в одну часть.

print('{:>3} {:>10} {:>10} {:>15}'.format('№', 'X', 'Y', 'Результат'))  # Печатаем шапку таблицы.
print('-' * 43)  # Печатаем линию под шапкой.
for shot in range(1, 11):  # Выполняем ровно десять выстрелов.
    x = uniform(-2.5, 2.5)  # Генерируем случайную координату X.
    y = uniform(-2.5, 2.5)  # Генерируем случайную координату Y.
    if is_hit(x, y):  # Проверяем попадание точки в область.
        result = 'Попадает'  # Запоминаем сообщение при попадании.
    else:  # Если точка вне области.
        result = 'Не попадает'  # Запоминаем сообщение о промахе.
    print('{:>3} {:>10.2f} {:>10.2f} {:>15}'.format(shot, x, y, result))  # Выводим координаты и результат.
