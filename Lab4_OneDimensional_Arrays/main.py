# Лабораторная работа №4. Одномерные массивы. Вариант 2.
from random import uniform  # Подключаем генератор случайных вещественных чисел.

n = int(input('Введите количество элементов N (от 2 до 30): '))  # Запрашиваем размер массива.
if n < 2 or n > 30:  # Проверяем допустимый размер массива.
    print('Ошибка: количество элементов должно быть от 2 до 30.')  # Сообщаем о неправильном размере.
else:  # Продолжаем, если размер массива допустим.
    numbers = []  # Создаём пустой список для чисел.
    for i in range(n):  # Повторяем заполнение N раз.
        numbers.append(round(uniform(-5.0, 5.0), 2))  # Добавляем случайное число от -5 до 5.
    print('\nИсходный массив:')  # Подписываем исходные данные.
    print(numbers)  # Выводим исходный список.

    positive_sum = 0.0  # Создаём переменную для суммы положительных элементов.
    for value in numbers:  # Перебираем все элементы списка.
        if value > 0:  # Проверяем, что элемент больше нуля.
            positive_sum += value  # Добавляем положительный элемент к сумме.

    max_abs_index = 0  # Сначала считаем, что максимум по модулю стоит на первой позиции.
    min_abs_index = 0  # Сначала считаем, что минимум по модулю стоит на первой позиции.
    for i in range(1, n):  # Проверяем остальные элементы массива.
        if abs(numbers[i]) > abs(numbers[max_abs_index]):  # Сравниваем модули для поиска максимума.
            max_abs_index = i  # Запоминаем индекс нового максимума по модулю.
        if abs(numbers[i]) < abs(numbers[min_abs_index]):  # Сравниваем модули для поиска минимума.
            min_abs_index = i  # Запоминаем индекс нового минимума по модулю.

    left_index = min(max_abs_index, min_abs_index) + 1  # Находим индекс первого элемента между экстремумами.
    right_index = max(max_abs_index, min_abs_index)  # Определяем правую границу, не включая её.
    product = 1.0  # Единица является начальным значением произведения.
    for i in range(left_index, right_index):  # Перебираем элементы строго между экстремумами.
        product *= numbers[i]  # Умножаем очередной элемент на текущее произведение.

    sorted_numbers = numbers.copy()  # Создаём копию, чтобы сохранить исходный массив.
    for i in range(n - 1):  # Выполняем проходы алгоритма сортировки обменами.
        for j in range(n - 1 - i):  # Сравниваем соседние элементы неотсортированной части.
            if sorted_numbers[j] < sorted_numbers[j + 1]:  # Проверяем порядок по убыванию.
                sorted_numbers[j], sorted_numbers[j + 1] = sorted_numbers[j + 1], sorted_numbers[j]  # Меняем элементы местами.

    print('\n1. Сумма положительных элементов: {:.2f}'.format(positive_sum))  # Показываем сумму положительных чисел.
    print('Максимальный по модулю элемент: {:.2f}, позиция: {}'.format(numbers[max_abs_index], max_abs_index + 1))  # Показываем максимум и его позицию.
    print('Минимальный по модулю элемент: {:.2f}, позиция: {}'.format(numbers[min_abs_index], min_abs_index + 1))  # Показываем минимум и его позицию.
    print('2. Произведение элементов между ними: {:.4f}'.format(product))  # Показываем произведение между найденными элементами.
    print('\nМассив по убыванию:')  # Подписываем отсортированный массив.
    print(sorted_numbers)  # Выводим список по убыванию.
input('\nНажмите Enter, чтобы закрыть программу...')  # Удерживаем окно открытым при запуске двойным нажатием.
